#!/bin/bash

# Setup script for Docusaurus v3 with TailwindCSS and DaisyUI

echo "Setting up Docusaurus v3 with TailwindCSS v4 and DaisyUI template..."

# Navigate to frontend directory
cd frontend

# Install dependencies
npm install

echo "Setup complete! You can now run:"
echo "npm start - to start the development server"
echo "npm run build - to build the static site"